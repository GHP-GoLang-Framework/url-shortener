package main

import (
	"context"
	"log"
	"net/http"
	"os"

	"url-shortener/internal/store"
)

// db is package-level so every generated page handler (same package main)
// can reach it directly without each .ghp page importing the store package.
var db *store.Store

func main() {
	ctx := context.Background()

	pgURL := getenv("DATABASE_URL", "postgres://ghp:ghp@localhost:5432/ghp_shortener?sslmode=disable")
	redisAddr := getenv("REDIS_ADDR", "localhost:6379")
	addr := getenv("ADDR", ":8080")

	var err error
	db, err = store.Open(ctx, pgURL, redisAddr)
	if err != nil {
		log.Fatalf("store.Open: %v", err)
	}
	defer db.Close()

	mux := http.NewServeMux()
	AddRoutes(mux) // generated by `ghp build` — registers GET for every page

	// ghp only emits GET routes today; the shorten form is a POST to the
	// same index page, so it's wired by hand onto the same handler.
	mux.HandleFunc("POST /", Index)

	log.Printf("listening on %s", addr)
	log.Fatal(http.ListenAndServe(addr, mux))
}

func getenv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}
